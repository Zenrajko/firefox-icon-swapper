const KEYS = { icons: "icSwapperIcons", pending: "icSwapperPending" };

const targetDetail = document.getElementById("target-detail");
const lightFile = document.getElementById("light-file");
const copySelect = document.getElementById("copy-select");
const iconPreview = document.getElementById("icon-preview");
const previewLoading = document.getElementById("preview-loading");
const previewRow = document.getElementById("preview-row");
const applyBtn = document.getElementById("apply-btn");
const section3 = document.getElementById("step3");
const statusEl = document.getElementById("apply-status");

const state = { target: null, icon: null, byId: new Map(), toolbarItems: [] };

async function getIcons() {
  return (await browser.storage.local.get(KEYS.icons))[KEYS.icons] || {};
}

function walk(nodes, out) {
  for (const n of nodes) {
    if (n.url) out.push(n);
    if (n.children) walk(n.children, out);
  }
}

function hostOf(url) {
  try {
    return new URL(url).hostname;
  } catch {
    return "";
  }
}

function itemToLabel(it) {
  const title = it.title || it.url;
  const host = hostOf(it.url);
  return host ? `${title} — ${host}` : title;
}

function itemToDetail(it) {
  return it.title ? `${it.title} — ${it.url}` : it.url;
}

function isReusable(it) {
  return /^https?:/.test(it.url);
}

async function toolbarChildren() {
  try {
    return await browser.bookmarks.getChildren("toolbar_____");
  } catch {
    const [root] = await browser.bookmarks.getTree();
    const toolbar = (root.children || []).find((n) => n.id === "toolbar_____");
    if (!toolbar) return [];
    const [sub] = await browser.bookmarks.getSubTree(toolbar.id);
    return sub.children || [];
  }
}

async function getToolbarBookmarks() {
  return (await toolbarChildren()).filter(isReusable);
}

function renderTarget(it) {
  targetDetail.textContent = "";
  if (!it) {
    targetDetail.textContent = "No bookmark selected.";
    return;
  }
  const title = document.createElement("div");
  title.className = "target-title";
  title.textContent = it.title || "(untitled)";
  const url = document.createElement("div");
  url.className = "target-url";
  url.textContent = it.url;
  targetDetail.append(title, url);
}

function setStatus(text, isError) {
  statusEl.textContent = text;
  statusEl.hidden = false;
  statusEl.classList.toggle("error", !!isError);
}

function cssEscape(s) {
  return String(s).replace(/\\/g, "\\\\").replace(/"/g, '\\"');
}

function generateCss(icons) {
  const lines = [];
  lines.push("/* Generated by Firefox Icon Swapper");
  lines.push("   Paste this block into chrome/userChrome.css in your profile folder and");
  lines.push("   restart Firefox. Requires toolkit.legacyUserProfileCustomizations.stylesheets = true. */");
  lines.push('@namespace url("http://www.mozilla.org/keymaster/gatekeeper/there.is.only.xul");');
  const entries = Object.entries(icons);
  if (!entries.length) {
    lines.push("/* No mappings yet. Add one in this options page first. */");
    return lines.join("\n");
  }
  for (const [id, m] of entries) {
    const selector = m.label
      ? `#PlacesToolbar .bookmark-item[label="${cssEscape(m.label)}"]`
      : `#PlacesToolbar .bookmark-item[label=""],\n#PlacesToolbar .bookmark-item:not([label])`;
    lines.push("");
    lines.push(`/* ${m.label || "(no title)"} (${id}) */`);
    lines.push(`${selector} {`);
    lines.push("  -moz-appearance: none !important;");
    lines.push(`  background-image: url("${m.light}") !important;`);
    lines.push("  background-repeat: no-repeat !important;");
    lines.push("  background-position: left center !important;");
    lines.push("  background-size: 16px 16px !important;");
    lines.push("  padding-inline-start: 18px !important;");
    lines.push("}");
    lines.push(`${selector} > .toolbarbutton-icon {`);
    lines.push("  display: none !important;");
    lines.push("}");
  }
  return lines.join("\n");
}

async function setLoading() {
  state.icon = null;
  iconPreview.hidden = true;
  previewLoading.hidden = false;
  previewRow.classList.add("visible");
}

async function copyText(text) {
  try {
    await navigator.clipboard.writeText(text);
  } catch {
    const ta = document.createElement("textarea");
    ta.value = text;
    ta.style.position = "fixed";
    ta.style.opacity = "0";
    document.body.appendChild(ta);
    ta.select();
    document.execCommand("copy");
    ta.remove();
  }
}

function enableSteps() {
  document.querySelectorAll("#step3 li.disabled").forEach((li) => li.classList.remove("disabled"));
}

function setIcon(dataUrl) {
  state.icon = dataUrl;
  iconPreview.src = dataUrl;
  iconPreview.hidden = false;
  previewLoading.hidden = true;
  previewRow.classList.add("visible");
  section3.hidden = false;
}

function clearPreview() {
  state.icon = null;
  previewRow.classList.remove("visible");
}

function readFile(input) {
  const file = input.files && input.files[0];
  if (!file) return;
  const reader = new FileReader();
  reader.onload = () => {
    copySelect.value = "";
    setIcon(reader.result);
  };
  reader.onerror = () => {
    setStatus("Couldn't read that file.", true);
    clearPreview();
  };
  setLoading();
  reader.readAsDataURL(file);
}

let toolbarPopulated = false;

function populateCopySelect() {
  if (toolbarPopulated) return;
  toolbarPopulated = true;
  let count = 0;
  for (const it of state.toolbarItems) {
    if (state.target && it.id === state.target.id) continue;
    const opt = document.createElement("option");
    opt.value = it.id;
    opt.textContent = itemToLabel(it);
    opt.title = itemToDetail(it);
    copySelect.appendChild(opt);
    count++;
  }
  copySelect.options[0].textContent = count
    ? `Choose a bookmark… (${count})`
    : "No other toolbar bookmarks";
}

copySelect.addEventListener("mousedown", () => {
  setTimeout(() => {
    copySelect.selectedIndex = copySelect.options.length - 1;
    copySelect.selectedIndex = 0;
  }, 0);
});

copySelect.addEventListener("focus", () => {
  clearPreview();
  populateCopySelect();
});

async function useBookmarkIcon(id) {
  const b = state.byId.get(id);
  if (!b) return;
  setLoading();
  try {
    const icons = await getIcons();
    const existing = icons[b.id];
    if (existing && existing.light) {
      setIcon(existing.light);
      statusEl.hidden = true;
      return;
    }
    const result = await browser.runtime.sendMessage({ type: "copySiteIcon", id: b.id });
    if (result && result.ok) {
      setIcon(result.dataUrl);
      statusEl.hidden = true;
    } else {
      setStatus((result && result.error) || "Couldn't copy that bookmark's icon.", true);
      clearPreview();
    }
  } catch (err) {
    setStatus(`Couldn't copy that bookmark's icon: ${err.message}`, true);
    clearPreview();
  }
}

async function applyIcons() {
  if (!state.target) return setStatus("Right-click a bookmark first (Set custom icon…).", true);
  if (!state.icon) return setStatus("Pick an icon file or copy one from another bookmark first.", true);

  const icons = await getIcons();
  const title = state.target.title || "";
  const untitled = state.toolbarItems.filter((b) => !b.title);
  if (!title && untitled.length > 1) {
    return setStatus(
      `This bookmark has no title and ${untitled.length} toolbar bookmarks have none either, so the CSS can't tell them apart. Give this one a short title first.`,
      true
    );
  }
  icons[state.target.id] = { label: title, light: state.icon };
  await browser.storage.local.set({ [KEYS.icons]: icons });

  await copyText(generateCss(icons));

  enableSteps();
  statusEl.hidden = true;
}

lightFile.addEventListener("change", (e) => readFile(e.target));
copySelect.addEventListener("change", (e) => {
  if (!e.target.value) return;
  lightFile.value = "";
  useBookmarkIcon(e.target.value);
});
applyBtn.addEventListener("click", applyIcons);

(async function init() {
  const tree = await browser.bookmarks.getTree();
  const items = [];
  walk(tree, items);
  items.sort((a, b) => (a.title || a.url).localeCompare(b.title || b.url));
  state.byId = new Map(items.map((it) => [it.id, it]));
  state.toolbarItems = (await getToolbarBookmarks()).sort((a, b) =>
    (a.title || a.url).localeCompare(b.title || b.url)
  );

  const pending = (await browser.storage.local.get(KEYS.pending))[KEYS.pending];
  await browser.storage.local.remove(KEYS.pending);

  if (!pending || !state.byId.has(pending.id)) {
    renderTarget(null);
    setStatus("Right-click a bookmark on the toolbar and choose Set custom icon…", true);
    applyBtn.disabled = true;
    return;
  }

  state.target = state.byId.get(pending.id);
  renderTarget(state.target);
  if (pending.action === "capture-error") {
    setStatus(`Capture failed for “${pending.label}”: ${pending.message}`, true);
  }
})();